/**
 * Compile src/theme/orgTheme.ts with `astryx theme build`, the pattern Astryx
 * documents for SSR apps: a static CSS file plus a built theme object, so
 * Theme skips runtime style injection and nothing flashes on hydration.
 *
 * Two deterministic fixups run after every build:
 * 1. The CLI writes em dashes into its generated headers; the repo bans them,
 *    so they become a colon.
 * 2. A root <Theme> mirrors data-astryx-theme onto <html>, which would make
 *    the @scope rules (prose colors, fonts, tokens) reach the whole page,
 *    including the org shell around the Astryx subtree. Excluding html as a
 *    scope root keeps the theme inside the <Theme> wrapper div only.
 * 3. The volatile `Generated: <timestamp>` header line is dropped so a rebuild
 *    with no source change produces no diff.
 *
 * It then derives src/theme/orgTheme.fallback.css for browsers without CSS
 * @scope (Firefox before 146, including Firefox ESR 140 in .browserslistrc).
 * Every rule inside each @scope block is re-emitted in the same layer under a
 * plain selector for the wrapper div, `:where([data-astryx-theme="org"]:not(html))`:
 *   :scope        -> :where(ROOT)            (zero specificity)
 *   .x[data-y]    -> :where(ROOT) .x[data-y] (same specificity as in @scope)
 * OrgAstryxTheme imports the fallback BEFORE orgTheme.css, so in browsers with
 * @scope the official rules win every tie and the fallback is inert. Tokens
 * never reach <html> (ROOT excludes it), and the file ships only with the
 * provider. Limitation: the @scope lower bound (`to ([data-astryx-theme])`) is
 * not reproduced, so nesting a different Astryx theme inside the org theme
 * is unsupported on the fallback path.
 */
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const bin = resolve(root, "node_modules/.bin/astryx");
const result = spawnSync(bin, ["theme", "build", "src/theme/orgTheme.ts", "-o", "src/theme/orgTheme.css"], {
  cwd: root,
  stdio: "inherit"
});
if (result.status !== 0) process.exit(result.status ?? 1);

const DASH = String.fromCharCode(0x2014);
for (const file of ["org.js", "org.d.ts", "org.variants.d.ts", "orgTheme.css"]) {
  const path = resolve(root, "src/theme", file);
  let text = readFileSync(path, "utf8");
  text = text.split(` ${DASH} `).join(": ").split(DASH).join(":");
  text = text.replace(/^ \* Generated: .*\n/m, "");
  if (file === "orgTheme.css") {
    const from = '@scope ([data-astryx-theme="org"]) to';
    const to = '@scope ([data-astryx-theme="org"]:not(html)) to';
    const count = text.split(from).length - 1;
    if (count === 0) throw new Error("orgTheme.css: expected @scope rules not found; review the fixup");
    text = text.split(from).join(to);
  }
  writeFileSync(path, text);
}

// ---- Fallback for browsers without @scope -------------------------------
const ROOT = '[data-astryx-theme="org"]:not(html)';
const SCOPE_PRELUDE = `@scope (${ROOT}) to ([data-astryx-theme])`;

/** Split CSS text into top-level {selector, body} blocks (comments removed first). */
function blocks(text) {
  const out = [];
  let cursor = 0;
  while (cursor < text.length) {
    const start = text.indexOf("{", cursor);
    if (start === -1) {
      if (text.slice(cursor).trim()) throw new Error(`fallback: unexpected trailing CSS: ${text.slice(cursor, cursor + 80)}`);
      break;
    }
    const selector = text.slice(cursor, start).trim();
    let end = start + 1;
    let depth = 1;
    for (; end < text.length && depth; end++) {
      if (text[end] === "{") depth++;
      if (text[end] === "}") depth--;
    }
    if (depth) throw new Error("fallback: unbalanced CSS block");
    out.push({ selector, body: text.slice(start + 1, end - 1) });
    cursor = end;
  }
  return out;
}

/** Split a selector list on top-level commas (not inside () or []). */
function splitList(value) {
  const parts = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < value.length; i++) {
    const c = value[i];
    if (c === "(" || c === "[") depth++;
    if (c === ")" || c === "]") depth--;
    if (c === "," && depth === 0) {
      parts.push(value.slice(start, i).trim());
      start = i + 1;
    }
  }
  parts.push(value.slice(start).trim());
  return parts;
}

function rewrite(selector) {
  return splitList(selector)
    .map((part) => {
      if (part === ":scope") return `:where(${ROOT})`;
      if (part.includes(":scope") || part.includes("&")) throw new Error(`fallback: unsupported scoped selector: ${part}`);
      return `:where(${ROOT}) ${part}`;
    })
    .join(",\n");
}

const themeCss = readFileSync(resolve(root, "src/theme/orgTheme.css"), "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
let fallback =
  "/*\n * Generated by scripts/build-org-theme.mjs from orgTheme.css. Do not edit.\n" +
  " * @scope-free copy of the org theme for browsers without @scope. Imported\n" +
  " * before orgTheme.css, so where @scope works the official rules win.\n */\n";
let scopedRules = 0;
for (const layer of blocks(themeCss)) {
  if (!layer.selector.startsWith("@layer ")) throw new Error(`fallback: unexpected top-level block: ${layer.selector}`);
  const layerName = layer.selector.slice(7).trim();
  for (const block of blocks(layer.body)) {
    // Plain (unscoped) rules such as :root color-scheme are already plain CSS.
    if (!block.selector.startsWith("@scope")) continue;
    if (block.selector.replace(/\s+/g, " ") !== SCOPE_PRELUDE) throw new Error(`fallback: unexpected @scope prelude: ${block.selector}`);
    const rules = blocks(block.body);
    if (!rules.length) continue;
    fallback += `@layer ${layerName} {\n`;
    for (const rule of rules) {
      if (rule.selector.startsWith("@")) throw new Error(`fallback: unsupported at-rule inside @scope: ${rule.selector}`);
      if (rule.body.includes("{")) throw new Error(`fallback: nested rule inside ${rule.selector}`);
      fallback += `${rewrite(rule.selector)} {${rule.body.replace(/\s+$/, "")}\n}\n`;
      scopedRules++;
    }
    fallback += "}\n";
  }
}
const fallbackRules = fallback.replace(/\/\*[\s\S]*?\*\//g, "");
if (/@scope|:scope/.test(fallbackRules)) throw new Error("fallback: @scope syntax leaked into fallback");
if (!scopedRules) throw new Error("fallback: no scoped rules found");
writeFileSync(resolve(root, "src/theme/orgTheme.fallback.css"), fallback);
console.log(`org theme built; generated files normalized; fallback has ${scopedRules} rules.`);
